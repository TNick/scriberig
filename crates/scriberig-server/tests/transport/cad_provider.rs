//! Verifies configured CAD provider capabilities reach remote clients.

use std::sync::Arc;

use scriberig_app::{
    ApplicationBackend, ApplicationContext, ApplicationError, ApplicationRequest,
    ApplicationResult, ApplicationService, CadProviderRegistry,
};
use scriberig_client::Client;
use scriberig_domain_cad::{
    CadExternalProvider, CadFormat, CadProviderDescriptor, CadProviderError, CadProviderErrorKind,
    CadProviderFeature, CadProviderFormatCapability, CadProviderImport,
    CadProviderOpaquePreservation, Drawing,
};
use scriberig_protocol::{CadProviderAvailability, CadProviderFormat};
use scriberig_server::InProcessTransport;

/// Supplies a read-only fake provider for remote capability discovery.
struct FakeDwgProvider;

impl CadExternalProvider for FakeDwgProvider {
    /// Returns fake provider identity, version, and fidelity.
    ///
    /// # Returns
    /// The fake provider's read-only DWG descriptor.
    fn descriptor(&self) -> CadProviderDescriptor {
        CadProviderDescriptor {
            id: "fixture.dwg".to_owned(),
            version: "1.0".to_owned(),
            formats: vec![CadProviderFormatCapability {
                format: CadFormat::Dwg,
                read: true,
                write: false,
                validate: false,
                opaque_preservation: CadProviderOpaquePreservation::Unproven,
                supported_features: vec![CadProviderFeature::Line],
            }],
            deployment_requirements: Vec::new(),
        }
    }

    /// Rejects parsing because this fixture tests capability discovery only.
    ///
    /// # Parameters
    /// - `_format`: Requested CAD format.
    /// - `_bytes`: Exact source bytes.
    ///
    /// # Returns
    /// An import result when parsing is available.
    ///
    /// # Errors
    /// Always returns `ReadFailed` because this fixture does not parse DWG.
    fn import(
        &self,
        _format: &CadFormat,
        _bytes: &[u8],
    ) -> Result<CadProviderImport, CadProviderError> {
        Err(CadProviderError {
            kind: CadProviderErrorKind::ReadFailed,
        })
    }

    /// Rejects output because the fake provider is read-only.
    ///
    /// # Parameters
    /// - `_format`: Requested output format.
    /// - `_drawing`: Candidate semantic drawing.
    /// - `_baseline`: Exact source bytes.
    ///
    /// # Returns
    /// Candidate package bytes when rendering is supported.
    ///
    /// # Errors
    /// Always returns `ReadOnly` for this fixture.
    fn render_candidate(
        &self,
        _format: &CadFormat,
        _drawing: &Drawing,
        _baseline: &[u8],
    ) -> Result<Vec<u8>, CadProviderError> {
        Err(CadProviderError {
            kind: CadProviderErrorKind::ReadOnly,
        })
    }

    /// Accepts validation because no output is generated by this fixture.
    ///
    /// # Parameters
    /// - `_format`: Candidate package format.
    /// - `_bytes`: Staged candidate bytes.
    /// - `_expected`: Expected semantic drawing.
    ///
    /// # Returns
    /// Unit when candidate bytes pass validation.
    ///
    /// # Errors
    /// Returns an error if validation fails.
    fn validate(
        &self,
        _format: &CadFormat,
        _bytes: &[u8],
        _expected: &Drawing,
    ) -> Result<(), CadProviderError> {
        Ok(())
    }
}

/// Supplies a minimal backend for runtime capability requests.
struct EmptyBackend;

impl ApplicationBackend for EmptyBackend {
    /// Rejects semantic execution because this test performs discovery only.
    ///
    /// # Parameters
    /// - `_context`: Trusted application caller context.
    /// - `_request`: Universal operation that was requested.
    ///
    /// # Returns
    /// A result if execution were supported by the test backend.
    ///
    /// # Errors
    /// Always returns unsupported-operation for this test fixture.
    fn execute(
        &self,
        _context: &ApplicationContext,
        _request: &ApplicationRequest,
    ) -> Result<ApplicationResult, ApplicationError> {
        Err(ApplicationError::UnsupportedOperation {
            operation: "capability test".to_owned(),
        })
    }
}

/// Exposes the configured provider's version and read-only fidelity to a remote client.
#[test]
fn configured_cad_provider_capability_survives_remote_round_trip() {
    let registry = CadProviderRegistry::new()
        .register(Arc::new(FakeDwgProvider))
        .expect("register fake provider");
    let service = ApplicationService::new(EmptyBackend).with_cad_provider_registry(registry);
    let client = Client::new(InProcessTransport::new(service));
    let response = client.capabilities().expect("runtime capabilities");

    assert_eq!(response.cad_providers.len(), 1);
    let provider = &response.cad_providers[0];
    assert_eq!(provider.format, CadProviderFormat::Dwg);
    assert_eq!(provider.availability, CadProviderAvailability::Available);
    assert_eq!(provider.provider_id.as_deref(), Some("fixture.dwg"));
    assert_eq!(provider.provider_version.as_deref(), Some("1.0"));
    assert!(provider.can_read);
    assert!(!provider.can_write);
    assert!(!provider.can_validate);
    assert_eq!(
        provider.opaque_preservation,
        scriberig_protocol::CadOpaquePreservation::Unproven
    );
}

/// Preserves initialization failure as a safe state without provider diagnostics.
#[test]
fn provider_initialization_failure_survives_remote_capability_discovery() {
    let registry = CadProviderRegistry::new()
        .register_initialization_failure(CadFormat::Dwg)
        .expect("register initialization failure");
    let service = ApplicationService::new(EmptyBackend).with_cad_provider_registry(registry);
    let client = Client::new(InProcessTransport::new(service));
    let response = client.capabilities().expect("runtime capabilities");

    let provider = response
        .cad_providers
        .iter()
        .find(|provider| provider.format == CadProviderFormat::Dwg)
        .expect("DWG provider state");
    assert_eq!(
        provider.availability,
        CadProviderAvailability::InitializationFailed
    );
    assert!(provider.provider_id.is_none());
    assert!(provider.provider_version.is_none());
    assert!(!provider.can_read && !provider.can_write && !provider.can_validate);
}
