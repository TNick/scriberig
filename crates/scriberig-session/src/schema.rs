//! Defines stable session vocabulary names.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
/// Session-domain structured value.
pub enum SessionEntityType {
    Session,
    Branch,
    Goal,
    HumanInput,
    AgentOutput,
    Observation,
    Question,
    Decision,
    ToolInvocation,
    ToolResult,
    BranchResult,
    Summary,
    Task,
    Turn,
    ModelInvocation,
    ModelOutput,
    Plan,
    PlanNode,
    PlanDependency,
    PlanMembership,
    PlanStructure,
    PlanRevision,
    PlanGate,
    PlanEvidence,
    PlanSummary,
    PlanSummaryLink,
    PlanAttempt,
}
impl SessionEntityType {
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Session => "Session",
            Self::Branch => "Branch",
            Self::Goal => "Goal",
            Self::HumanInput => "HumanInput",
            Self::AgentOutput => "AgentOutput",
            Self::Observation => "Observation",
            Self::Question => "Question",
            Self::Decision => "Decision",
            Self::ToolInvocation => "ToolInvocation",
            Self::ToolResult => "ToolResult",
            Self::BranchResult => "BranchResult",
            Self::Summary => "Summary",
            Self::Task => "Task",
            Self::Turn => "Turn",
            Self::ModelInvocation => "ModelInvocation",
            Self::ModelOutput => "ModelOutput",
            Self::Plan => "scriberig.session.plan",
            Self::PlanNode => "scriberig.session.plan-node",
            Self::PlanDependency => "scriberig.session.plan-dependency",
            Self::PlanMembership => "scriberig.session.plan-membership",
            Self::PlanStructure => "scriberig.session.plan-structure",
            Self::PlanRevision => "scriberig.session.plan-revision",
            Self::PlanGate => "scriberig.session.plan-gate",
            Self::PlanEvidence => "scriberig.session.plan-evidence",
            Self::PlanSummary => "scriberig.session.plan-summary",
            Self::PlanSummaryLink => "scriberig.session.plan-summary-link",
            Self::PlanAttempt => "scriberig.session.plan-attempt",
        }
    }
}
